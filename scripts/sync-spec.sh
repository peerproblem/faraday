#!/bin/bash
# Copies the shared types from server/src/spec to client/src/lib/spec. The server copy is the source.
# --check exits 1 when the client copy is out of date.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/server/src/spec"
DST="$ROOT/client/src/lib/spec"
HEADER="// Generated by scripts/sync-spec.sh from server/src/spec. Do not edit."
render() { printf '%s\n' "$HEADER"; cat "$1"; }
if [ "${1:-}" = "--check" ]; then
  status=0
  for f in "$SRC"/*.ts; do
    n=$(basename "$f")
    if ! diff -q <(render "$f") "$DST/$n" >/dev/null 2>&1; then echo "out of date: client/src/lib/spec/$n"; status=1; fi
  done
  for f in "$DST"/*.ts; do [ -f "$SRC/$(basename "$f")" ] || { echo "stale: client/src/lib/spec/$(basename "$f")"; status=1; }; done
  exit $status
fi
mkdir -p "$DST"
rm -f "$DST"/*.ts
for f in "$SRC"/*.ts; do render "$f" > "$DST/$(basename "$f")"; done
echo "synced $(ls "$SRC"/*.ts | wc -l | tr -d ' ') files"
